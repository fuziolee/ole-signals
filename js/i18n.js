let lang = 'id';
try {
  const saved = localStorage.getItem('ole-lang');
  if (saved === 'id' || saved === 'en') lang = saved;
} catch (e) { /* abaikan: tanpa localStorage tetap jalan */ }

export function getLang() { return lang; }

export function setLang(next) {
  if (next !== 'id' && next !== 'en') return;
  lang = next;
  try { localStorage.setItem('ole-lang', next); } catch (e) { /* abaikan */ }
  document.documentElement.lang = next;
}

// t('key', {var: 'nilai'}) — ganti {var} di dalam string.
export function t(key, vars) {
  const dict = STR[lang] || STR.id;
  let s = dict[key] !== undefined ? dict[key] : (STR.id[key] !== undefined ? STR.id[key] : key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}
